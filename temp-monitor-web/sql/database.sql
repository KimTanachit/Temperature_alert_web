CREATE TABLE IF NOT EXISTS temperature_readings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reading_date DATE NOT NULL,
  reading_time TIME NOT NULL,
  temperature NUMERIC(6,2) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_temperature_created_at
  ON temperature_readings (created_at);

CREATE TABLE IF NOT EXISTS alerts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  temperature NUMERIC(6,2) NOT NULL,
  threshold NUMERIC(6,2) NOT NULL,
  line_sent BOOLEAN NOT NULL DEFAULT FALSE,
  message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_alerts_created_at
  ON alerts (created_at);

CREATE TABLE IF NOT EXISTS settings (
  id INTEGER PRIMARY KEY,
  danger_threshold NUMERIC(6,2) NOT NULL DEFAULT 100,
  reset_threshold NUMERIC(6,2) NOT NULL DEFAULT 100,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO settings (id, danger_threshold, reset_threshold)
VALUES (1, 100, 100)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS device_status (
  id INTEGER PRIMARY KEY,
  device_name VARCHAR(100) NOT NULL,
  wifi_status BOOLEAN DEFAULT FALSE,
  sensor_status BOOLEAN DEFAULT FALSE,
  battery_percent NUMERIC(5,2),
  last_seen TIMESTAMPTZ
);

INSERT INTO device_status (id, device_name)
