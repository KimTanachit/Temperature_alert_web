-- ตัวอย่างข้อมูล 30 วัน ทุก 3 นาที (ประมาณ 14,401 แถว)
-- รันส่วนนี้ครั้งเดียวถ้าต้องการข้อมูลทดสอบกราฟ
INSERT INTO temperature_readings (reading_date, reading_time, temperature, created_at)
SELECT
  (t AT TIME ZONE 'Asia/Bangkok')::DATE,
  (t AT TIME ZONE 'Asia/Bangkok')::TIME,
  ROUND((CASE
    WHEN EXTRACT(HOUR FROM (t AT TIME ZONE 'Asia/Bangkok')) BETWEEN 13 AND 14
         AND MOD(EXTRACT(DAY FROM (t AT TIME ZONE 'Asia/Bangkok'))::INT, 5) = 0
      THEN 101 + RANDOM() * 10
    ELSE 30 + RANDOM() * 25
  END)::NUMERIC, 2),
  t
FROM generate_series(
  NOW() - INTERVAL '30 days', NOW(), INTERVAL '3 minutes'
) AS t;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'user'
    CHECK (role IN ('user', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_username
  ON users (username);